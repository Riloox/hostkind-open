/* ------------------------------------------------------ 1. world headers -- */

test('the header accepts a world and refuses everything that is not one', () => {
  const good = worlds.readWorldHeader(worldBuffer({ version: 279, revision: 12, favorite: true }));
  assert.strictEqual(good.ok, true);
  assert.strictEqual(good.version, 279);
  assert.strictEqual(good.revision, 12);
  assert.strictEqual(good.favorite, true);
  // This buffer carries no header section, so the descriptive fields are
  // unknown - which is reported as unknown, never as a default.
  assert.strictEqual(good.gameMode, null);
  assert.strictEqual(good.worldName, null);
  assert.strictEqual(good.width, null);

  assert.strictEqual(worlds.readWorldHeader(worldBuffer().subarray(0, 12)).reason, 'truncated');
  assert.strictEqual(worlds.readWorldHeader(Buffer.alloc(0)).reason, 'truncated');
  assert.strictEqual(worlds.readWorldHeader(worldBuffer({ signature: 'relogiX' })).reason, 'not_a_world');
  assert.strictEqual(worlds.readWorldHeader(worldBuffer({ fileType: 1 })).reason, 'map_file');
  assert.strictEqual(worlds.readWorldHeader(worldBuffer({ fileType: 3 })).reason, 'player_file');
  // A valid signature with an implausible version is an unsupported version; a
  // file with no signature is simply not a world, whatever its first four bytes
  // happen to say.
  assert.strictEqual(worlds.readWorldHeader(worldBuffer({ version: 12 })).reason, 'unsupported_version');
});

test('the header section yields the world name, game mode and size', () => {
  // The four difficulties Hostkind offers, in the order Terraria stores them.
  // Confirmed against real generated worlds: classic 0, expert 1, master 2,
  // journey 3 - the same order `DIFFICULTIES` uses.
  const modes = ['classic', 'expert', 'master', 'journey'];
  modes.forEach((mode, value) => {
    const header = worlds.readWorldHeader(worldWithHeaderSection({ name: `World ${mode}`, gameMode: value }));
    assert.strictEqual(header.ok, true);
    assert.strictEqual(header.gameMode, mode, `game mode ${value} should read as ${mode}`);
    assert.strictEqual(header.worldName, `World ${mode}`);
    assert.strictEqual(header.width, 4200);
    assert.strictEqual(header.height, 1200);
  });

  const large = worlds.readWorldHeader(worldWithHeaderSection({ width: 8400, height: 2400 }));
  assert.strictEqual(large.width, 8400);
  assert.strictEqual(large.height, 2400);

  // A non-ASCII name survives the round trip: the length prefix counts bytes,
  // not characters, and getting that wrong would truncate the name.
  const accented = worlds.readWorldHeader(worldWithHeaderSection({ name: 'Mundo Pequeno' }));
  assert.strictEqual(accented.worldName, 'Mundo Pequeno');
});

test('a header section that cannot be trusted reports unknown, not a guess', () => {
  // A format too old for the game-mode field still yields the name, which has
  // been the first field of the section since the signature block existed.
  const old = worlds.readWorldHeader(worldWithHeaderSection({ version: 194, name: 'Old World' }));
  assert.strictEqual(old.ok, true);
  assert.strictEqual(old.worldName, 'Old World');
  assert.strictEqual(old.gameMode, null);

  // A mode outside the four that exist means the walk landed somewhere wrong.
  const bogusMode = worlds.readWorldHeader(worldWithHeaderSection({ gameMode: 47 }));
  assert.strictEqual(bogusMode.ok, true);
  assert.strictEqual(bogusMode.gameMode, null);

  // As does an implausible world size.
  const bogusSize = worlds.readWorldHeader(worldWithHeaderSection({ width: 3, height: 1 }));
  assert.strictEqual(bogusSize.gameMode, null);
  assert.strictEqual(bogusSize.width, null);

  // A section pointer past the end of what was read, and a section count that
  // is plainly garbage: both unknown, and neither an error - the file is still
  // a valid world by its signature.
  const beyond = worlds.readWorldHeader(worldWithHeaderSection({ section0: 900000 }));
  assert.strictEqual(beyond.ok, true);
  assert.strictEqual(beyond.worldName, null);

  // A pointer landing inside the preamble is equally wrong, in the other
  // direction: the header section can never start before the table that names it.
  const backwards = worlds.readWorldHeader(worldWithHeaderSection({ section0: 8 }));
  assert.strictEqual(backwards.ok, true);
  assert.strictEqual(backwards.worldName, null);

  const garbage = worldBuffer();
  garbage.writeInt16LE(9999, 24);
  assert.strictEqual(worlds.readWorldHeader(garbage).ok, true);
  assert.strictEqual(worlds.readWorldHeader(garbage).worldName, null);
});

test('a Minecraft level.dat and random bytes are not worlds', () => {
  // level.dat is gzip: 1f 8b 08 ...
  const levelDat = Buffer.concat([Buffer.from([0x1f, 0x8b, 0x08, 0x00]), Buffer.alloc(64, 9)]);
  assert.strictEqual(worlds.readWorldHeader(levelDat).ok, false);
  for (let i = 0; i < 25; i++) {
    const random = require('crypto').randomBytes(256);
    assert.strictEqual(worlds.readWorldHeader(random).ok, false, 'random bytes parsed as a world');
  }
});

