/*
 * A world file with a real header.
 *
 * The layout is the documented one every world since Terraria 1.3.0.1 carries:
 * an int32 format version, the ASCII signature "relogic", a file-type byte, a
 * revision counter and a flags qword. `readWorldHeader` reads exactly this much,
 * so this is the whole contract - and the negative fixtures below are what prove
 * it is not matching anything that merely looks close.
 */
function worldBuffer({ version = 279, signature = 'relogic', fileType = 2, revision = 3, favorite = false, extra = 4096 } = {}) {
  const header = Buffer.alloc(24 + extra);
  header.writeInt32LE(version, 0);
  Buffer.from(signature, 'ascii').copy(header, 4);
  header.writeUInt8(fileType, 11);
  header.writeUInt32LE(revision, 12);
  header.writeBigUInt64LE(favorite ? 1n : 0n, 16);
  // The rest is world data as far as this module is concerned.
  header.fill(0x2a, 24);
  return header;
}

/*
 * A world carrying a real header section, laid out exactly as a Terraria world
 * is: the section pointer table, the tile-frame-important bits, then the header
 * section itself. The layout was confirmed byte-for-byte against worlds
 * generated by a real 1.4.5.6 dedicated server (format 319), one per difficulty;
 * this builder is that layout, so a change to the parser that stops matching a
 * real file fails here rather than in front of an operator.
 */
function netString(value) {
  const body = Buffer.from(value, 'utf8');
  const length = [];
  let remaining = body.length;
  do {
    let byte = remaining & 0x7f;
    remaining >>>= 7;
    if (remaining) byte |= 0x80;
    length.push(byte);
  } while (remaining);
  return Buffer.concat([Buffer.from(length), body]);
}

function worldWithHeaderSection({
  version = 319, name = 'Fixture', seed = 'seed', gameMode = 0,
  width = 4200, height = 1200, sections = 11, tileMaskBits = 753, section0 = null,
} = {}) {
  const preamble = Buffer.alloc(24 + 2 + 4 * sections + 2 + Math.ceil(tileMaskBits / 8));
  preamble.writeInt32LE(version, 0);
  Buffer.from('relogic', 'ascii').copy(preamble, 4);
  preamble.writeUInt8(2, 11);
  preamble.writeUInt32LE(2, 12);
  preamble.writeBigUInt64LE(0n, 16);
  preamble.writeInt16LE(sections, 24);
  // Section 0 starts where the preamble ends; the rest of the table is not read.
  preamble.writeInt32LE(section0 == null ? preamble.length : section0, 26);
  preamble.writeInt16LE(tileMaskBits, 26 + 4 * sections);

  const numbers = Buffer.alloc(8 + 16 + 4 + 16 + 12);
  let at = 0;
  numbers.writeBigUInt64LE(1370094567425n, at); at += 8;   // world generator version
  at += 16;                                                 // guid
  numbers.writeInt32LE(17750398, at); at += 4;              // world id
  numbers.writeInt32LE(0, at); at += 4;                     // left
  numbers.writeInt32LE(width * 16, at); at += 4;            // right
  numbers.writeInt32LE(0, at); at += 4;                     // top
  numbers.writeInt32LE(height * 16, at); at += 4;           // bottom
  numbers.writeInt32LE(height, at); at += 4;                // height precedes width
  numbers.writeInt32LE(width, at); at += 4;
  numbers.writeInt32LE(gameMode, at);

  return Buffer.concat([preamble, netString(name), netString(seed), numbers, Buffer.alloc(512, 0x2a)]);
}

