test('case-only collisions are refused on Windows semantics and allowed elsewhere', () => {
  assert.strictEqual(worlds.sameFile('World.wld', 'world.wld', { caseInsensitive: true }), true);
  assert.strictEqual(worlds.sameFile('World.wld', 'world.wld', { caseInsensitive: false }), false);

  // The collision check reads the directory, so a name differing only in case is
  // a collision exactly when the host would treat the two as one file.
  const desc = makeServer({ worldNames: ['World'] });
  const saveDir = worlds.resolveSaveDir(desc);
  assert.throws(() => worlds.previewGenerate({
    desc, actorId: ACTOR, input: { name: 'World', size: 'small' }, manager: fakeManager(),
  }), /already exists/);
  assert.ok(saveDir.rel === 'worlds');
});

test('the save directory comes from the descriptor, the config, or nowhere at all', () => {
  const fromDescriptor = makeServer();
  assert.strictEqual(worlds.resolveSaveDir(fromDescriptor).source, 'descriptor');
  assert.strictEqual(worlds.resolveSaveDir(fromDescriptor).rel, 'worlds');

  // No descriptor field: the server's own worldpath is authoritative.
  const fromConfig = makeServer();
  delete fromConfig.terrariaSaveDir;
  assert.strictEqual(worlds.resolveSaveDir(fromConfig).source, 'config');

  // Neither: refused with a reason, never defaulted to a guessed folder.
  const unknown = makeServer({ config: '# nothing here\nport=7777\n' });
  delete unknown.terrariaSaveDir;
  assert.throws(() => worlds.resolveSaveDir(unknown), (err) => err.code === 'save_dir_unknown');

  // A worldpath outside the server folder is not usable either.
  const outside = makeServer({ config: `worldpath=${path.join(ROOT, 'elsewhere')}\n` });
  delete outside.terrariaSaveDir;
  assert.throws(() => worlds.resolveSaveDir(outside), (err) => err.code === 'save_dir_unknown');
});

test('a save directory reached through a link is refused rather than followed', function () {
  const desc = makeServer({ worldNames: [] });
  const outside = path.join(ROOT, `link-target-${++seq}`);
  fs.mkdirSync(outside, { recursive: true });
  try { fs.symlinkSync(outside, path.join(desc.dir, 'linked')); }
  catch { return; } // unprivileged Windows: nothing to test
  desc.terrariaSaveDir = 'linked';
  assert.throws(() => worlds.resolveSaveDir(desc), (err) => err.code === 'symlink_path');
});

