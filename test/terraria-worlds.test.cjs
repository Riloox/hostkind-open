test('a no-op parse and serialize is byte-identical, for every shape', () => {
  const shapes = [
    'a=1\nb=2\n',
    'a=1\r\nb=2\r\n',
    '\ufefflead=1\n',
    '# comment\n\n  spaced = value  \nempty=\n',
    'no-trailing-newline=1',
    'mixed=1\r\nendings=2\n',
    'value=has=equals\nnonascii=Zoë Müller\n',
    '',
  ];
  for (const text of shapes) {
    assert.strictEqual(terrariaConfig.serialize(terrariaConfig.parse(text)), text, `round trip changed ${JSON.stringify(text)}`);
  }
});

test('a one-key edit changes only that line', () => {
  const text = '# header\r\nworld=old\r\n\r\nmotd=hi\r\n';
  const { document, diff } = terrariaConfig.patch(terrariaConfig.parse(text), { world: 'new' });
  assert.deepStrictEqual(diff, [{ key: 'world', from: 'old', to: 'new' }]);
  assert.strictEqual(terrariaConfig.serialize(document), '# header\r\nworld=new\r\n\r\nmotd=hi\r\n');

  // An absent key is appended with the file's own line ending; a removal takes
  // the whole line.
  const appended = terrariaConfig.patch(terrariaConfig.parse(text), { seed: 'x' });
  assert.strictEqual(terrariaConfig.serialize(appended.document), `${text}seed=x\r\n`);
  const removed = terrariaConfig.patch(terrariaConfig.parse(text), { world: null });
  assert.strictEqual(terrariaConfig.serialize(removed.document), '# header\r\n\r\nmotd=hi\r\n');
});

test('a duplicated key is refused rather than resolved, and a line break is never written', () => {
  const document = terrariaConfig.parse('world=a\nworld=b\n');
  assert.throws(() => terrariaConfig.patch(document, { world: 'c' }), (err) => err.code === 'duplicate_key');
  assert.throws(() => terrariaConfig.get(document, 'world'), (err) => err.code === 'duplicate_key');
  assert.throws(() => terrariaConfig.patch(terrariaConfig.parse('a=1\n'), { a: 'x\ny=2' }), (err) => err.code === 'invalid_value');
  // Whitespace around a key and its separator survives an edit.
  const spaced = terrariaConfig.patch(terrariaConfig.parse('  world =  old\n'), { world: 'new' });
  assert.strictEqual(terrariaConfig.serialize(spaced.document), '  world =  new\n');
});

