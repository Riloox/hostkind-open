/*
 * A Terraria server folder: an installation with a `worlds/` save directory, a
 * serverconfig.txt that points into it, and an executable the generation tests
 * can be pointed at without ever running it.
 */
function makeServer({ worldNames = ['World'], variant = 'vanilla', modData = false, config = CONFIG_TEXT, saveDir = 'worlds' } = {}) {
  const id = `srv-${++seq}`;
  const dir = path.join(ROOT, id);
  const save = path.join(dir, saveDir);
  fs.mkdirSync(save, { recursive: true });
  for (const name of worldNames) {
    fs.writeFileSync(path.join(save, `${name}.wld`), worldBuffer());
    if (modData) fs.writeFileSync(path.join(save, `${name}.twld`), Buffer.alloc(128, 7));
  }
  const executable = path.join(dir, 'TerrariaServer.bin.x86_64');
  fs.writeFileSync(executable, '#!/bin/false\n');
  const configFile = path.join(dir, 'serverconfig.txt');
  fs.writeFileSync(configFile, config.replaceAll('WORLDPATH', save));
  return {
    id,
    name: `Server ${id}`,
    type: 'terraria',
    dir,
    cwd: dir,
    executable,
    args: ['-config', configFile],
    port: 7777,
    terrariaVariant: variant,
    terrariaSaveDir: saveDir,
    terrariaWorld: worldNames.length ? { file: `${saveDir}/${worldNames[0]}.wld`, name: worldNames[0] } : null,
  };
}

// A descriptor store that behaves like config.json does: the runner writes
// through `saveDescriptor` and verifies through `readDescriptor`, and those must
// not be the same object.
function descriptorStore(desc, { failSave = false, failRevert = false } = {}) {
  const live = { ...desc };
  return {
    desc: live,
    saved: [],
    saveDescriptor(fields) {
      if (failSave) throw new Error('config.json is read-only in this test');
      for (const [key, value] of Object.entries(fields)) {
        if (value === null) delete live[key];
        else live[key] = value;
      }
      this.saved.push(fields);
    },
    readDescriptor() {
      if (failRevert) return { ...live, terrariaWorld: null };
      return JSON.parse(JSON.stringify(live));
    },
  };
}

