// A store-only zip built byte by byte. archiver normalizes `../` out of entry
// names and cannot emit a symlink entry, so a hostile archive built with it
// would silently test nothing.
function makeZip(dest, entries) {
  const chunks = [];
  const central = [];
  let offset = 0;
  const push = (buffer) => { chunks.push(buffer); offset += buffer.length; };
  for (const entry of entries) {
    const name = Buffer.from(entry.name, 'utf8');
    const data = Buffer.isBuffer(entry.data) ? entry.data : Buffer.from(entry.data == null ? '' : entry.data);
    const crc = zlib.crc32(data);
    const mode = entry.mode == null ? 0o100644 : entry.mode;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    const localOffset = offset;
    push(local); push(name); push(data);
    const record = Buffer.alloc(46);
    record.writeUInt32LE(0x02014b50, 0);
    record.writeUInt16LE((3 << 8) | 20, 4);
    record.writeUInt16LE(20, 6);
    record.writeUInt32LE(crc, 16);
    record.writeUInt32LE(data.length, 20);
    record.writeUInt32LE(data.length, 24);
    record.writeUInt16LE(name.length, 28);
    record.writeUInt32LE(mode * 0x10000, 38);
    record.writeUInt32LE(localOffset, 42);
    central.push(Buffer.concat([record, name]));
  }
  const centralOffset = offset;
  for (const record of central) push(record);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(central.length, 8);
  end.writeUInt16LE(central.length, 10);
  end.writeUInt32LE(offset - centralOffset, 12);
  end.writeUInt32LE(centralOffset, 16);
  push(end);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, Buffer.concat(chunks));
  return dest;
}

// Stage an upload the way lib/routes/terraria.cjs does, without the HTTP layer.
function stageUpload(files, { kind = 'upload' } = {}) {
  const dir = worlds.importStagingDir(`stage-${++seq}`);
  fs.mkdirSync(path.join(dir, 'payload'), { recursive: true });
  for (const [name, data] of Object.entries(files)) {
    fs.writeFileSync(path.join(dir, 'payload', name), data);
  }
  return { dir, kind, archive: kind === 'archive' ? path.join('payload', 'upload.zip') : null, originalName: Object.keys(files)[0] };
}

// A generation that writes the world the real server would have written.
function generationStub({ produce = true, modData = false, fail = null, onSpawn = null } = {}) {
  return async ({ launch, onProgress, operationId }) => {
    if (onSpawn) onSpawn({ launch, operationId });
    onProgress({ percent: 0, stage: null });
    onProgress({ percent: 50, stage: 'Generating world terrain', stagePercent: 12 });
    if (fail) throw fail;
    if (produce) {
      // The staging config is what tells the server where to write, so the stub
      // reads it back rather than being told: a runner that stopped repointing
      // the config would fail here instead of passing.
      const document = terrariaConfig.parse(fs.readFileSync(launch.args[launch.args.indexOf('-config') + 1], 'utf8'));
      const target = terrariaConfig.get(document, 'world');
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, worldBuffer());
      if (modData) fs.writeFileSync(target.replace(/\.wld$/, '.twld'), Buffer.alloc(64, 3));
    }
    onProgress({ percent: 100, stage: 'Finalizing world', stagePercent: 0 });
    return { code: 0, signal: null, requestedExit: true, generating: true };
  };
}

