test('a verified snapshot is taken before every destructive run', async () => {
  const desc = makeServer({ worldNames: ['World', 'Second'] });
  const store = descriptorStore(desc);
  const taken = [];
  const realTake = snapshots.take;
  snapshots.take = (args) => { taken.push(args); return realTake(args); };
  try {
    const preview = worlds.previewSelect({ desc: store.desc, actorId: ACTOR, file: 'Second.wld', manager: fakeManager() });
    await runOperation(worlds.KIND.SELECT, (operationId) => worlds.runSelect({
      desc: store.desc, manager: fakeManager(), operationId, preview,
      saveDescriptor: (fields) => store.saveDescriptor(fields),
      readDescriptor: () => store.readDescriptor(),
    }));
    const del = worlds.previewDelete({ desc: store.desc, actorId: ACTOR, file: 'World.wld', manager: fakeManager() });
    await runOperation(worlds.KIND.DELETE, (operationId) => worlds.runDelete({
      desc: store.desc, manager: fakeManager(), operationId, preview: del, actorId: ACTOR,
      saveDescriptor: (fields) => store.saveDescriptor(fields),
      readDescriptor: () => store.readDescriptor(),
    }));
  } finally {
    snapshots.take = realTake;
  }
  assert.strictEqual(taken.length, 2, 'a run went ahead without a snapshot');
  assert.deepStrictEqual(taken[0].scope, ['serverconfig.txt']);
  assert.deepStrictEqual(taken[1].scope, ['worlds']);
});

